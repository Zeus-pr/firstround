async function authHeaders(user: User): Promise<HeadersInit> {
  const token = await user.getIdToken();
  return {
    Authorization: `Bearer ${token}`,
    Accept: 'application/json',
    'Content-Type': 'application/json',
  };
}

export async function fetchCatalog(user: User): Promise<CatalogLists> {
  const res = await fetch(apiUrl('/preferences/catalog'), { headers: await authHeaders(user) });
  if (!res.ok) return FALLBACK_CATALOG;
  const json = (await res.json()) as { lists?: Partial<CatalogLists> };
  const lists = json.lists;
  if (!lists) return FALLBACK_CATALOG;
  const merged = { ...FALLBACK_CATALOG };
  (Object.keys(FALLBACK_CATALOG) as (keyof CatalogLists)[]).forEach((key) => {
    const extra = lists[key] ?? [];
    const seen = new Set(merged[key].map((item) => item.toLowerCase()));
    for (const item of extra) {
      if (!seen.has(item.toLowerCase())) merged[key].push(item);
    }
  });
  return merged;
}

export async function addCatalogOption(
  user: User,
  kind: keyof CatalogLists,
  label: string,
): Promise<CatalogLists> {
  const res = await fetch(apiUrl('/preferences/catalog'), {
    method: 'POST',
    headers: await authHeaders(user),
    body: JSON.stringify({ kind, label }),
  });
  if (!res.ok) {
    const current = FALLBACK_CATALOG[kind];
    if (!current.some((item) => item.toLowerCase() === label.toLowerCase())) current.push(label);
    return FALLBACK_CATALOG;
  }
  const json = (await res.json()) as { lists: CatalogLists };
  return json.lists;
}
